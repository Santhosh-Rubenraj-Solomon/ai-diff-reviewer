import { describe, expect, test } from 'bun:test';
import { classify, describeSkip, extensionOf, languageOf, type FilterInput } from '../src/diff/filter.ts';
import {
  lineSlice,
  renderNumberedContent,
  renderNumberedDiff,
  renderSymbolOutline,
} from '../src/diff/render.ts';
import { parseHunks } from '../src/diff/parse.ts';
import type { ChangedFile, SkipReason } from '../src/types.ts';

function input(overrides: Partial<FilterInput>): FilterInput {
  return {
    path: 'src/a.ts',
    status: 'modified',
    content: 'export const a = 1;\n',
    maxFileBytes: 1024,
    ...overrides,
  };
}

describe('extensionOf / languageOf', () => {
  test('takes the last extension, lowercased', () => {
    expect(extensionOf('src/App.TSX')).toBe('tsx');
    expect(extensionOf('a/b/c.d.ts')).toBe('ts');
  });

  test('a dotfile or extensionless path has no extension', () => {
    expect(extensionOf('.gitignore')).toBe('');
    expect(extensionOf('Makefile')).toBe('');
    expect(extensionOf('dir.with.dots/README')).toBe('');
  });

  test('maps known extensions and returns null otherwise', () => {
    expect(languageOf('x.py')).toBe('python');
    expect(languageOf('x.mjs')).toBe('javascript');
    expect(languageOf('x.unknownext')).toBeNull();
    expect(languageOf('Dockerfile')).toBeNull();
  });
});

describe('classify', () => {
  test('reviews an ordinary source file', () => {
    expect(classify(input({}))).toBeNull();
  });

  test('deleted wins over everything else', () => {
    expect(classify(input({ status: 'deleted', path: 'node_modules/x.png', content: null }))).toBe('deleted');
  });

  test('platform binary flag is honoured', () => {
    expect(classify(input({ platformSaysBinary: true }))).toBe('binary');
  });

  test('binary extensions are skipped regardless of case', () => {
    expect(classify(input({ path: 'assets/Logo.PNG' }))).toBe('binary');
  });

  test('lockfiles at any depth', () => {
    expect(classify(input({ path: 'package-lock.json' }))).toBe('lockfile');
    expect(classify(input({ path: 'apps/web/pnpm-lock.yaml' }))).toBe('lockfile');
    expect(classify(input({ path: 'go.sum' }))).toBe('lockfile');
  });

  test('vendored directories, including root-level ones', () => {
    expect(classify(input({ path: 'node_modules/left-pad/index.js' }))).toBe('vendored');
    expect(classify(input({ path: 'pkg/vendor/x/y.go' }))).toBe('vendored');
    expect(classify(input({ path: 'web/.next/server.js' }))).toBe('vendored');
  });

  test('generated by path pattern', () => {
    expect(classify(input({ path: 'public/app.min.js' }))).toBe('generated');
    expect(classify(input({ path: 'api/user.pb.go' }))).toBe('generated');
    expect(classify(input({ path: 'src/__snapshots__/a.test.ts.snap' }))).toBe('generated');
    expect(classify(input({ path: 'db/migrations/2024/001.sql' }))).toBe('generated');
  });

  test('a non-migration sql file is reviewed', () => {
    expect(classify(input({ path: 'db/queries/report.sql' }))).toBeNull();
  });

  test('size limit uses the explicit sizeBytes when given', () => {
    expect(classify(input({ sizeBytes: 2048 }))).toBe('too-large');
    expect(classify(input({ sizeBytes: 1024 }))).toBeNull();
  });

  test('size limit counts utf8 bytes, not characters', () => {
    // 400 three-byte characters = 1200 bytes > 1024, but only 400 chars.
    expect(classify(input({ content: '€'.repeat(400) }))).toBe('too-large');
  });

  test('null content on a non-deleted file is a named skip', () => {
    expect(classify(input({ content: null }))).toBe('no-content');
  });

  test('a NUL byte early in the content means binary', () => {
    expect(classify(input({ content: 'abc\u0000def' }))).toBe('binary');
  });

  test('a NUL byte past the first 8 KiB does not', () => {
    const content = 'a'.repeat(9000) + '\u0000';
    expect(classify(input({ content, maxFileBytes: 100_000 }))).toBeNull();
  });

  test('an @generated marker in the header means generated', () => {
    expect(classify(input({ content: '// @generated by protoc\nexport {}' }))).toBe('generated');
    expect(classify(input({ content: '# @generated\nx = 1', path: 'x.py' }))).toBe('generated');
  });

  test('an @generated mention deep in the file does not count', () => {
    const content = 'x\n'.repeat(1100) + '// @generated';
    expect(classify(input({ content, maxFileBytes: 100_000 }))).toBeNull();
  });

  test('a mid-line @generated mention is not a marker', () => {
    expect(classify(input({ content: 'const note = "see @generated docs";' }))).toBeNull();
  });
});

describe('describeSkip', () => {
  test('every skip reason has a human-readable description', () => {
    const reasons: SkipReason[] = [
      'binary',
      'vendored',
      'generated',
      'lockfile',
      'too-large',
      'deleted',
      'ignored',
      'no-content',
    ];
    for (const reason of reasons) {
      const text = describeSkip(reason);
      expect(typeof text).toBe('string');
      expect(text.length).toBeGreaterThan(0);
    }
  });
});

function changedFile(overrides: Partial<ChangedFile> = {}): ChangedFile {
  return {
    path: 'src/a.ts',
    status: 'modified',
    hunks: parseHunks(['@@ -8,3 +8,3 @@', ' keep', '-old', '+new', ' tail'].join('\n')),
    headContent: null,
    contentHash: '',
    language: 'typescript',
    additions: 1,
    deletions: 1,
    ...overrides,
  };
}

describe('renderNumberedDiff', () => {
  test('numbers head-side lines and leaves removed lines unnumbered', () => {
    const out = renderNumberedDiff(changedFile(), 'abcdef0123456789');
    expect(out.split('\n')).toEqual([
      '--- src/a.ts (modified, head abcdef0) ---',
      '   8 | keep',
      '-    | old',
      '+  9 | new',
      '  10 | tail',
    ]);
  });

  test('pads to the width of the largest head line', () => {
    const file = changedFile({
      hunks: parseHunks(['@@ -98,1 +98,3 @@', ' a', '+b', '+c'].join('\n')),
    });
    const lines = renderNumberedDiff(file, 'x'.repeat(40)).split('\n');
    expect(lines[1]).toBe('   98 | a');
    expect(lines[3]).toBe('+ 100 | c');
  });

  test('separates hunks with an ellipsis', () => {
    const file = changedFile({
      hunks: parseHunks(['@@ -1,1 +1,1 @@', '-a', '+b', '@@ -20,1 +20,1 @@', '-c', '+d'].join('\n')),
    });
    expect(renderNumberedDiff(file, 'h')).toContain('...');
  });

  test('names the previous path of a rename', () => {
    const out = renderNumberedDiff(changedFile({ status: 'renamed', oldPath: 'src/old.ts' }), 'h');
    expect(out.split('\n')[0]).toContain('renamed from src/old.ts');
  });

  test('a file with no hunks renders only the header', () => {
    expect(renderNumberedDiff(changedFile({ hunks: [] }), 'h')).toBe('--- src/a.ts (modified, head h) ---');
  });
});

describe('renderNumberedContent / lineSlice / renderSymbolOutline', () => {
  test('numbers every line from the start line', () => {
    expect(renderNumberedContent('a\nb', 9)).toBe(' 9 | a\n10 | b');
  });

  test('lineSlice clamps at the start and end of the file', () => {
    const content = ['l1', 'l2', 'l3', 'l4', 'l5'].join('\n');
    expect(lineSlice(content, 1, 1)).toBe('1 | l1\n2 | l2');
    expect(lineSlice(content, 5, 1)).toBe('4 | l4\n5 | l5');
    expect(lineSlice(content, 3, 10).split('\n')).toHaveLength(5);
  });

  test('outline says so when there are no symbols', () => {
    expect(renderSymbolOutline([])).toBe('(no exported symbols detected)');
  });

  test('outline is capped at 200 symbols', () => {
    const symbols = Array.from({ length: 250 }, (_, i) => ({ name: `s${i}`, kind: 'const', line: i + 1 }));
    const out = renderSymbolOutline(symbols).split('\n');
    expect(out).toHaveLength(200);
    expect(out[0]).toBe('    1 | const s0');
  });
});
