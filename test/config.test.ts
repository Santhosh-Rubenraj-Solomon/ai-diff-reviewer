import { describe, expect, test } from 'bun:test';
import { ConfigError, loadConfig, unpricedModels } from '../src/config.ts';
import { parseArgs } from '../src/cli.ts';
import { classify, languageOf } from '../src/diff/filter.ts';
import { priceUsd } from '../src/review/pricing.ts';

describe('loadConfig', () => {
  test('reads GitLab CI variables directly', () => {
    const cfg = loadConfig({
      CI_API_V4_URL: 'https://gitlab.example.com/api/v4',
      CI_MERGE_REQUEST_PROJECT_ID: '77',
      CI_MERGE_REQUEST_IID: '12',
      REVIEWER_TOKEN: 'secret',
    });
    expect(cfg.platform).toBe('gitlab');
    expect(cfg.projectId).toBe('77');
    expect(cfg.requestId).toBe('12');
    expect(cfg.apiUrl).toBe('https://gitlab.example.com/api/v4');
  });

  test('reads GitHub Actions variables directly', () => {
    const cfg = loadConfig({
      GITHUB_REPOSITORY: 'owner/repo',
      GITHUB_TOKEN: 'secret',
      REVIEWER_MR_IID: '5',
    });
    expect(cfg.platform).toBe('github');
    expect(cfg.projectId).toBe('owner/repo');
    expect(cfg.apiUrl).toBe('https://api.github.com');
  });

  test('fails a hosted run with no token rather than late', () => {
    expect(() =>
      loadConfig({ REVIEWER_PLATFORM: 'gitlab', REVIEWER_PROJECT_ID: '1', REVIEWER_MR_IID: '2' }),
    ).toThrow(ConfigError);
  });

  test('defaults to local with no CI variables at all', () => {
    expect(loadConfig({}).platform).toBe('local');
  });

  test('CLI overrides beat the environment', () => {
    const cfg = loadConfig({ REVIEWER_CONTEXT: 'full' }, { context: 'off' });
    expect(cfg.context).toBe('off');
  });

  test('an unpriced model is named, not billed at zero', () => {
    const cfg = loadConfig({}, { reviewModel: 'claude-made-up-9' });
    expect(unpricedModels(cfg)).toContain('claude-made-up-9');
    expect(priceUsd('claude-made-up-9', { inputTokens: 1000, outputTokens: 1000 })).toBeNull();
  });

  test('a Jev judge without a key fails at config time, not mid-run', () => {
    expect(() => loadConfig({}, { judgeModel: 'jev-1.13', judge: 'on' })).toThrow(/Jev judge/);
  });

  test('a Jev judge accepts any of the three key variables', () => {
    for (const key of ['REVIEWER_JEV_API_KEY', 'TYPESAFE_API_KEY', 'OPENROUTER_API_KEY']) {
      const cfg = loadConfig({ [key]: 'k' }, { judgeModel: 'jev-1.13', judge: 'on' });
      expect(cfg.jev.apiKey).toBe('k');
    }
  });

  test('Jev prices input only — output is unmetered', () => {
    expect(priceUsd('jev-1.13', { inputTokens: 1_000_000, outputTokens: 500_000 })).toBeCloseTo(
      0.042,
      6,
    );
  });

  test('a known model prices from the table', () => {
    expect(priceUsd('claude-opus-5', { inputTokens: 1_000_000, outputTokens: 0 })).toBeCloseTo(5, 6);
  });
});

describe('parseArgs', () => {
  test('accepts --key=value and --key value', () => {
    const args = parseArgs(['review', '--mr=12', '--platform', 'gitlab', '--dry-run']);
    expect(args.command).toEqual(['review']);
    expect(args.flags.get('mr')).toBe('12');
    expect(args.flags.get('platform')).toBe('gitlab');
    expect(args.flags.get('dry-run')).toBe(true);
  });

  test('rejects negation flags instead of silently ignoring them', () => {
    // `--no-x` under meow-style parsing becomes a no-op nobody notices.
    expect(() => parseArgs(['review', '--no-judge'])).toThrow(/Negation flags/);
  });
});

describe('file filtering', () => {
  const base = { status: 'modified' as const, maxFileBytes: 1024 };

  test('matches a nested node_modules path', () => {
    expect(classify({ ...base, path: 'app/node_modules/pkg/index.js', content: 'x' })).toBe(
      'vendored',
    );
  });

  test('skips lockfiles, binaries and generated output by name', () => {
    expect(classify({ ...base, path: 'pnpm-lock.yaml', content: 'x' })).toBe('lockfile');
    expect(classify({ ...base, path: 'assets/logo.png', content: 'x' })).toBe('binary');
    expect(classify({ ...base, path: 'src/app.min.js', content: 'x' })).toBe('generated');
  });

  test('detects a generated marker in the file body', () => {
    expect(classify({ ...base, path: 'src/api.ts', content: '// @generated by protoc\nx' })).toBe(
      'generated',
    );
  });

  test('skips files over the size limit', () => {
    expect(classify({ ...base, path: 'src/big.ts', content: 'x'.repeat(2000) })).toBe('too-large');
  });

  test('reviews an ordinary source file', () => {
    expect(classify({ ...base, path: 'src/app.ts', content: 'const a = 1;' })).toBeNull();
  });

  test('knows common languages', () => {
    expect(languageOf('src/a.tsx')).toBe('typescript');
    expect(languageOf('main.go')).toBe('go');
    expect(languageOf('LICENSE')).toBeNull();
  });
});
